package com.nexora.repository;

import com.nexora.model.ProjectReport;
import com.nexora.model.enums.ReportType;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.stereotype.Repository;

import java.util.List;

@Repository
public interface ProjectReportRepository extends JpaRepository<ProjectReport, Long> {
    List<ProjectReport> findByProjectIdOrderByGeneratedAtDesc(Long projectId);
    List<ProjectReport> findByReportTypeOrderByGeneratedAtDesc(ReportType reportType);
    List<ProjectReport> findByProjectIdAndReportType(Long projectId, ReportType reportType);
    long countByAutoGeneratedTrue();
}
