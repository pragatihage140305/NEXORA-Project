    @Override
    public void run(String... args) {
        // Relax check constraints generated by older enum definitions in H2
        try {
            List<String> projectChecks = jdbcTemplate.queryForList(
                    "SELECT CONSTRAINT_NAME FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE UPPER(TABLE_NAME) = 'PROJECTS' AND CONSTRAINT_TYPE = 'CHECK'",
                    String.class
            );
            for (String cName : projectChecks) {
                jdbcTemplate.execute("ALTER TABLE projects DROP CONSTRAINT IF EXISTS " + cName);
            }

            List<String> protoChecks = jdbcTemplate.queryForList(
                    "SELECT CONSTRAINT_NAME FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE UPPER(TABLE_NAME) = 'PROTOTYPE_VERSIONS' AND CONSTRAINT_TYPE = 'CHECK'",
                    String.class
            );
            for (String cName : protoChecks) {
                jdbcTemplate.execute("ALTER TABLE prototype_versions DROP CONSTRAINT IF EXISTS " + cName);
            }
        } catch (Exception ex) {
            System.out.println("Constraint relaxation notice: " + ex.getMessage());
        }

        if (userRepository.count() == 0) {
            seedInitialDatabase();
        }
        seedTeam3AndDemoProject();
    }

