package com.nexora.model;

import com.nexora.model.enums.ReportType;
import jakarta.persistence.*;
import java.time.LocalDateTime;

@Entity
@Table(name = "project_reports")
public class ProjectReport {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "project_id", nullable = false)
    private Project project;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private ReportType reportType;

    @Column(nullable = false)
    private String title;

    @Column(length = 4000)
    private String summary;

    @Column(columnDefinition = "TEXT")
    private String metricsJson;

    @Column(columnDefinition = "TEXT")
    private String contentJson;

    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "generated_by_id")
    private User generatedBy;

    private boolean autoGenerated = true;

    private LocalDateTime generatedAt = LocalDateTime.now();

    public ProjectReport() {}

    public ProjectReport(Project project, ReportType reportType, String title, String summary, String metricsJson, String contentJson, User generatedBy, boolean autoGenerated) {
        this.project = project;
        this.reportType = reportType;
        this.title = title;
        this.summary = summary;
        this.metricsJson = metricsJson;
        this.contentJson = contentJson;
        this.generatedBy = generatedBy;
        this.autoGenerated = autoGenerated;
        this.generatedAt = LocalDateTime.now();
    }

    // Getters and Setters
    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public Project getProject() { return project; }
    public void setProject(Project project) { this.project = project; }

    public ReportType getReportType() { return reportType; }
    public void setReportType(ReportType reportType) { this.reportType = reportType; }

    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }

    public String getSummary() { return summary; }
    public void setSummary(String summary) { this.summary = summary; }

    public String getMetricsJson() { return metricsJson; }
    public void setMetricsJson(String metricsJson) { this.metricsJson = metricsJson; }

    public String getContentJson() { return contentJson; }
    public void setContentJson(String contentJson) { this.contentJson = contentJson; }

    public User getGeneratedBy() { return generatedBy; }
    public void setGeneratedBy(User generatedBy) { this.generatedBy = generatedBy; }

    public boolean isAutoGenerated() { return autoGenerated; }
    public void setAutoGenerated(boolean autoGenerated) { this.autoGenerated = autoGenerated; }

    public LocalDateTime getGeneratedAt() { return generatedAt; }
    public void setGeneratedAt(LocalDateTime generatedAt) { this.generatedAt = generatedAt; }
}
