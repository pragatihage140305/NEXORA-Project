package com.nexora.service.dto;

import com.nexora.model.ProjectReport;
import com.nexora.model.enums.ReportType;

public class ReportDto {

    public record GenerateReportRequest(
            Long projectId,
            ReportType reportType,
            String customNotes
    ) {}

    public record ReportResponse(
            Long id,
            Long projectId,
            String projectTitle,
            String projectCode,
            ReportType reportType,
            String title,
            String summary,
            String metricsJson,
            String contentJson,
            Long generatedById,
            String generatedByName,
            boolean autoGenerated,
            String generatedAt
    ) {
        public static ReportResponse from(ProjectReport r) {
            return new ReportResponse(
                    r.getId(),
                    r.getProject().getId(),
                    r.getProject().getTitle(),
                    r.getProject().getProjectCode(),
                    r.getReportType(),
                    r.getTitle(),
                    r.getSummary(),
                    r.getMetricsJson(),
                    r.getContentJson(),
                    r.getGeneratedBy() != null ? r.getGeneratedBy().getId() : null,
                    r.getGeneratedBy() != null ? r.getGeneratedBy().getName() : "System Automated Engine",
                    r.isAutoGenerated(),
                    r.getGeneratedAt().toString()
            );
        }
    }

    public record CreateExpenseRequest(
            Long projectId,
            String category,
            Double amount,
            String currency,
            String description,
            String expenseDate
    ) {}

    public record ExpenseResponse(
            Long id,
            Long projectId,
            String projectTitle,
            String category,
            Double amount,
            String currency,
            String description,
            String recordedByName,
            String expenseDate,
            String createdAt
    ) {}
}
